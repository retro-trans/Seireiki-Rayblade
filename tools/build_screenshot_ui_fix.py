def skies_mask(text, glyphs):
    # One half scale for the entire line; no per-letter squeezing or outlines.
    pieces = []
    for ch in text:
        if ch == ' ':
            pieces.append(Image.new('L', (6, 24)))
        else:
            glyph = glyphs[ch]
            box = glyph.getbbox()
            width = ((box[2]-box[0]+1)//2)*2
            item = Image.new('L', (width+2, 24))
            item.paste(glyph.crop((box[0], 0, box[2], 24)), (0, 0))
            pieces.append(item)
    line = Image.new('L', (sum(p.width for p in pieces), 24))
    x = 0
    for p in pieces:
        line.paste(p, (x, 0)); x += p.width
    return np.asarray(line.resize((line.width//2, 12), Image.Resampling.BOX))


def blend_1555(plane, mask, x, y, color):
    for yy, xx in zip(*np.nonzero(mask)):
        alpha = int(mask[yy, xx]); old = int(plane[y+yy, x+xx]); value = 0x8000
        for shift, channel in zip((10, 5, 0), color):
            base = (old >> shift) & 31
            value |= ((base*(255-alpha)+channel*alpha+127)//255) << shift
        plane[y+yy, x+xx] = value


def win_fix(source):
    skies, _ = read_executable()
    glyphs = {chr(i): skies_glyph(skies, i, LEVELS) for i in range(32, 127)}
    replacements, raws, previews, labels = {}, {}, {}, []
    packed = member(source, 83); old, _ = decompress(packed[16:]); before = plane(old); target = before.copy()
    # Header text only; the icon, blue frame, album photograph and book stay exact.
    box = (111, 24, 225, 40); x0, y0, x1, y1 = box
    for y in range(y0, y1):
        # A neutral left-to-right fill matches the sign paper. Sampling x109
        # directly would repeat the neighboring icon's blue strokes as lines.
        for x in range(x0, x1):
            t = (x-x0)/(x1-x0-1)
            channels = [round(a*(1-t)+b*t) for a,b in zip((27,27,23),(25,25,21))]
            target[y, x] = 0x8000 | channels[0]<<10 | channels[1]<<5 | channels[2]
    mask = skies_mask('Memory Album', glyphs)
    x = x0+(x1-x0-mask.shape[1])//2; y = 25
    assert x >= x0 and x+mask.shape[1] <= x1 and y+12 <= y1
    blend_1555(target, mask, x, y, (25, 1, 3))
    outside = np.ones(before.shape, bool); outside[y0:y1, x0:x1] = False
    assert np.array_equal(before[outside], target[outside])
    replacements[83], raws[83] = texture(packed, target)
    previews['album-heading'] = (decode_pvr(old)[0], decode_pvr(raws[83])[0])
    packed = member(source, 88); old, _ = decompress(packed[16:]); before = plane(old); target = before.copy()
    rows = [r for r in json_read(ROOT/'work/translation/en/ui/image-labels.en.json')['rows'] if r['texture_member'] == 88]
    protected = np.ones(before.shape, bool)
    for row in rows:
        x0, y0, x1, y1 = row['source_box']; cell = target[y0:y1, x0:x1]
        # Restore flat tab interior, preserving its metal rim, bevel and tip.
        left, right = (6, cell.shape[1]-4)
        fill = int(before[y0+2, x0+left])
        interior = cell[2:14, left:right]
        interior[interior & 0x8000 != 0] = fill
        mask = skies_mask(row['en'], glyphs)
        assert mask.shape[1]+1 <= right-left, (row['en'], mask.shape, right-left)
        x = left+(right-left-mask.shape[1]-1)//2; y = 2
        blend_1555(cell, mask, x+1, y+1, (2, 2, 2))
        blend_1555(cell, mask, x, y, (31, 31, 31))
        protected[y0:y1, x0:x1] = False
        labels.append({'id': row['id'], 'en': row['en'], 'box': row['source_box'], 'mask_size': list(reversed(mask.shape))})
    assert np.array_equal(before[protected], target[protected])
    replacements[88], raws[88] = texture(packed, target)
    previews['battle-tabs'] = (decode_pvr(old)[0], decode_pvr(raws[88])[0])
    archive, packing = repack(source, replacements, first=struct.unpack_from('<I', source, 8)[0])
    assert all(member(source, i) == member(archive, i) for i in range(90) if i not in replacements)
    return archive, raws, previews, {'header': 'Memory Album', 'labels': labels,
        'font': 'Original Skies Latin glyphs at uniform 1/2 scale; replaces historical supplied-bitmap labels only.',
        'VRAM_change_bytes': 0, 'protected': 'Native runtime font, all sprite geometry, other 88 members and untouched atlas pixels.',
        'packing': packing}


@lru_cache(maxsize=1)
def compose():
    base = ROOT/'work/output'/PRIOR
    old_exe = (base/'1ST_READ.BIN').read_bytes(); assert digest(old_exe) == SOURCE_EXE_SHA
    exe = bytearray(old_exe)
    edits = []
    # These two callers alone place weapon attributes. Preserve the hardware-
    # passing bytewise name-width routine, all row/index arithmetic and sprites.
    for at, expected, replacement, label in (
        (0x4f924, bytes.fromhex('f4852970'), bytes.fromhex('58e00040'), 'P marker x176'),
        (0x4f95a, bytes.fromhex('f4852970'), bytes.fromhex('5ce00040'), 'W marker x184')):
        assert old_exe[at:at+4] == expected, (hex(at), old_exe[at:at+4].hex())
        exe[at:at+4] = replacement
        edits.append({'offset': hex(at), 'before': expected.hex(), 'after': replacement.hex(), 'purpose': label})
    names = {r['id']: r for r in json_read(ROOT/'work/translation/en/ui/names.json')}
    recipe = json_read(base/'ui-layouts.en.json')
    changes = {}
    for index, text in ((176, 'By HP'), (177, 'By Prana'), (178, 'By LV'), (179, 'By EXP')):
        key = f'names.g00.{index:03d}'; row = names[key]
        recipe['rows'][key] = {'en': text, 'source_sha256': row['source_sha256'],
            'prior_en_sha256': digest(row['en'].encode()), 'reason': 'Fit the existing sort box using compact, consistent sort labels.'}
        changes[key] = text
    decoded, packed, names_report = names_compose(overrides=recipe['rows'], version=VERSION)
    assert len(packed) <= len((base/'text/D_NAMES.BIN').read_bytes())
    packed += bytes(len((base/'text/D_NAMES.BIN').read_bytes())-len(packed))
    recipe.update(version=VERSION, previous_build=PRIOR)
    album, album_raw, album_previews, album_report = album_fix((base/'ALBUM.AFS').read_bytes())
    win, win_raw, previews, win_report = win_fix((base/'WIN00.AFS').read_bytes())
    files = {'1ST_READ.BIN': bytes(exe), 'D_NAMES.BIN': packed, 'ALBUM.AFS': album, 'WIN00.AFS': win}
    require_native_layouts({k:v for k,v in files.items() if k.endswith('.AFS')})
    report = {'version': VERSION, 'source_build': PRIOR, 'date': '2026-11-26', 'release': False,
        'files': {k: {'sha256': digest(v), 'size': len(v)} for k,v in files.items()},
        'executable_edits': edits, 'sort_labels': changes, 'album': album_report, 'artwork': win_report,
        'battle_cutin': 'All ranged attacks reportedly lose animation on hardware; owner reports Flycast unaffected. No fix claimed.',
        'hardware_runtime': 'Every executable byte outside the two weapon-marker coordinate sites is exact 0.7.50; Native font member and allocator unchanged.',
        'live_validation': 'Pending: desktop keyboard input denied. Public 0.7.50 DCP renders opening movie in Flycast; user reports it works.'}
    return files, decoded, recipe, names_report, report, album_raw, win_raw, album_previews, previews


def write_components():
    result = compose(); files, decoded, recipe, names_report, report, _, _, album_previews, previews = result
    OUT.mkdir(parents=True, exist_ok=True); UI.mkdir(parents=True, exist_ok=True)
    for name, data in files.items(): (OUT/name).write_bytes(data)
    (OUT/'D_NAMES.en.dec.bin').write_bytes(decoded)
    for name, data in (('ui-layouts.en.json', recipe), ('names-component-report.json', names_report), ('screenshot-ui-component.json', report)):
        save(OUT/name, data)
    for n, im in album_previews.items(): im.save(UI/f'caption-square-{n}.png')
    for name, (before, after) in previews.items():
        sheet = Image.new('RGBA', (before.width*2, before.height+24), '#383838')
        sheet.alpha_composite(before, (0, 24)); sheet.alpha_composite(after, (before.width, 24))
        ImageDraw.Draw(sheet).text((4, 4), 'Before / after - asset preview, not gameplay', fill='white')
        sheet.save(UI/f'{name}-before-after.png')
    return result


